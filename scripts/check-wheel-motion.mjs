import { chromium, expect } from "@playwright/test";
import fs from "node:fs/promises";
import { rewardDay, prizeRoll } from "../src/rewards.js";
const browser = await chromium.launch({ channel: "msedge" });
const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
const base = process.env.DEMO_URL || "http://localhost:5173/", errors = [];
page.on("pageerror",(e)=>errors.push(e.message));
page.on("console",(m)=>{if(m.type()==="error")errors.push(m.text());});
await fs.mkdir("tmp/roulette-v12",{recursive:true});
const roll=async(index)=>page.evaluate((value)=>{crypto.getRandomValues=(a)=>{a[0]=Math.floor(value*4294967296);return a;};},prizeRoll(index));
try {
  await page.addInitScript((day)=>{
    if(localStorage.getItem("reel-seeded"))return;
    localStorage.setItem("reel-seeded","true");
    localStorage.setItem("rakurs:pdfOnboardingSeen","true");
    localStorage.setItem("rakurs:demoUser",JSON.stringify({name:"Алина",telegramId:123456,method:"telegram"}));
    localStorage.setItem("rakurs:rewardsWallet",JSON.stringify({balance:40,lastShownDay:day}));
  },rewardDay());
  await page.goto(base+"#/profile");
  await page.locator(".profile-wheel-card").click();
  await page.waitForTimeout(600);
  const first=await page.locator('.reel-card[data-absolute="0"]').boundingBox();
  await page.waitForTimeout(500);
  const second=await page.locator('.reel-card[data-absolute="0"]').boundingBox();
  expect(second.y).toBeLessThan(first.y-3);
  await page.screenshot({path:"tmp/roulette-v12/idle.png"});
  await roll(7);
  const spin=page.locator(".wheel-spin-button");
  await spin.click();await expect(spin).toBeDisabled();await spin.dispatchEvent("click");
  await expect.poll(()=>page.evaluate(()=>JSON.parse(localStorage.getItem("rakurs:rewardsWallet")).spinCount)).toBe(1);
  await page.waitForTimeout(500);
  await expect(page.locator(".roulette-result")).toHaveCount(0);
  await page.screenshot({path:"tmp/roulette-v12/spinning.png"});
  await expect(page.locator(".result-copy")).toContainText("Скидка 30%",{timeout:8500});
  const selected=await page.locator(".reel-cards").evaluate((el)=>{
    const mid=el.getBoundingClientRect().y+el.getBoundingClientRect().height/2;
    return [...el.children].map((c)=>({id:c.dataset.prizeId,d:Math.abs(c.getBoundingClientRect().y+c.getBoundingClientRect().height/2-mid)})).sort((a,b)=>a.d-b.d)[0];
  });
  expect(selected.id).toBe("discount30");expect(selected.d).toBeLessThan(2);
  await expect(page.locator(".prize-validity time")).toHaveText(/23:59:\d{2}/);
  await page.waitForTimeout(850);
  await page.screenshot({path:"tmp/roulette-v12/coupon-win.png"});
  await page.getByRole("button",{name:"К рулетке",exact:true}).click();
  await roll(3);await spin.click();await page.waitForTimeout(350);await page.reload();
  await expect(page.locator(".profile-prizes-link")).toContainText("Сохранено выигрышей: 2");
  await page.locator(".profile-wheel-card").click();
  await expect(page.locator(".result-copy")).toContainText("Бесплатный прогноз");
  const wallet=await page.evaluate(()=>JSON.parse(localStorage.getItem("rakurs:rewardsWallet")));
  expect(wallet.balance).toBe(20);expect(wallet.spinCount).toBe(2);expect(wallet.coupons).toHaveLength(1);
  expect(wallet.prizes.filter(p=>p.prize.kind==="forecast")).toHaveLength(1);
  await page.waitForTimeout(800);await page.screenshot({path:"tmp/roulette-v12/recovered-forecast.png"});
  await page.getByRole("button",{name:"Воспользоваться",exact:true}).click();
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await page.goto(base+"#/match/fox-metro");
  await page.getByRole("button",{name:/Купить прогноз/}).click();
  await page.getByRole("button",{name:"Использовать анализ",exact:true}).click();
  await expect(page.locator(".analysis-dashboard")).toBeVisible();
  await page.goto(base+"#/profile");await page.locator(".profile-prizes-link").click();
  await expect(page.locator(".prize-grid-card.state-used")).toHaveCount(1);
  await page.screenshot({path:"tmp/roulette-v12/my-prizes.png"});
  expect(errors).toEqual([]);
  console.log("PASS: idle vertical motion, accelerated reel and matching winning card, exact cost/duplicate guard, expiry, reload recovery, saved prizes and forecast consumption.");
} finally {await browser.close();}
